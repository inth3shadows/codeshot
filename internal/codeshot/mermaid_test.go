func TestBuildArchitectureMermaidDrawsTheSameGraphAsDot(t *testing.T) {
	edges := []FileEdge{
		{From: "src/a.go", To: "lib/b.go", Weight: 5},
		{From: "src/a_test.go", To: "src/a.go", Weight: 2},
		{From: "src/a.go", To: "db/q.go", Weight: 1},
	}
	opt := ArchOptions{MaxRender: Unlimited, Violating: map[string]bool{drawnEdgeKey("src/a.go", "db/q.go"): true}}
	got := BuildArchitectureMermaid(edges, opt)
	want := strings.Join([]string{
		"flowchart LR",
		"  classDef default fill:#f8fafc,stroke:#cbd5e1,color:#334155",
		"  classDef test fill:#f8fafc,stroke:#cbd5e1,color:#334155,stroke-dasharray:4 3",
		`  n0("src/a.go")`,
		`  n1("lib/b.go")`,
		`  n2("src/a_test.go"):::test`,
		`  n3("db/q.go")`,
		`  n0 -->|"5"| n1`,
		`  n2 -->|"2"| n0`,
		`  n0 -->|"1"| n3`,
		"  linkStyle 2 stroke:#dc2626,color:#dc2626,stroke-width:2px",
	}, "\n")
	if got != want {
		t.Errorf("got:\n%s\nwant:\n%s", got, want)
	}
	// --max-render keeps the same files in both formats.
	opt.MaxRender = 2
	dotFiles := regexp.MustCompile(`(?m)^  "([^"]+)"(?: \[[^]]*\])?;$`).FindAllStringSubmatch(BuildArchitectureDot(edges, opt), -1)
	mmdFiles := regexp.MustCompile(`(?m)^  n[0-9]+\("([^"]+)"\)`).FindAllStringSubmatch(BuildArchitectureMermaid(edges, opt), -1)
	var a, b []string
	for _, m := range dotFiles {
		a = append(a, m[1])
	}
	for _, m := range mmdFiles {
		b = append(b, m[1])
	}
	if !slices.Equal(a, b) || len(a) != 2 {
		t.Errorf("--max-render 2: dot %v, mermaid %v", a, b)
	}
}

func TestBuildArchitectureMermaidMultiSourceAndEscaping(t *testing.T) {
	edges := []FileEdge{
		{From: `a "q" #1 <x>.go`, To: "b.go", Weight: 5, Seen: []SourceWeight{{"cg", 3}, {"scip", 5}}, Full: []string{"cg", "scip"}},
		{From: "b.go", To: "c.go", Weight: 2, Seen: []SourceWeight{{"scip", 2}}, Full: []string{"scip"}},
	}
	got := BuildArchitectureMermaid(edges, ArchOptions{MaxRender: Unlimited, Sources: []string{"cg", "scip"}})
	wantMatch(t, `(?s)^---\ntitle: "Sources: cg, scip\. Dashed: not every source saw all of the edge; its label gives each source's own weight\."\n---\nflowchart LR\n`, got)
	wantMatch(t, `n0\("a #34;q#34; #35;1 #60;x#62;\.go"\)`, got)
	wantMatch(t, `n0 -->\|"5"\| n1`, got)
	wantMatch(t, `n1 -\.->\|"scip 2"\| n2`, got)
}

func TestMermaidTitleAndLimits(t *testing.T) {
	wantMatch(t, "^flowchart LR\n  accTitle: Architecture — generated by codeshot\n  classDef", mermaidWithTitle(BuildArchitectureMermaid(nil, ArchOptions{MaxRender: Unlimited}), "Architecture — generated by codeshot"))
	if w := MermaidLimitWarning(strings.Repeat("  n0 -->|\"1\"| n1\n", 500)); w != "" {
		t.Errorf("500 edges warned: %s", w)
	}
	wantMatch(t, `has 501 edges .* GitHub renders at most 500 edges`, MermaidLimitWarning(strings.Repeat("  n0 -->|\"1\"| n1\n", 501)))
	wantMatch(t, `GitHub renders at most 500 edges and 50000 characters`, MermaidLimitWarning(strings.Repeat("x", 50001)))
	if !IsBlankDot(BuildArchitectureMermaid(nil, ArchOptions{MaxRender: Unlimited})) {
		t.Error("an empty Mermaid diagram is not blank")
	}
	if IsBlankDot(BuildArchitectureMermaid([]FileEdge{{From: "a", To: "b", Weight: 1}}, ArchOptions{MaxRender: Unlimited})) {
		t.Error("a Mermaid diagram with nodes is blank")
	}
}

// End to end from a snapshot with no graphviz on PATH: --out writes the
// .mmd text, --embed puts a mermaid block in the doc and no image file,
// --check compares it, and symbol mode refuses the format.
func TestCLIMermaidNeedsNoGraphvizAndEmbedsABlock(t *testing.T) {
	t.Setenv("PATH", t.TempDir())
	if _, err := exec.LookPath("dot"); err == nil {
		t.Skip("dot still on PATH")
	}
	dir := t.TempDir()
	snap := "snapshot:" + writeSnapshotFile(t, cliSnapshot)
	out := filepath.Join(dir, "arch.mmd")
	if code, _, stderr := runCLI("--architecture", "--source", snap, "--format", "mermaid", "--out", out); code != 0 {
		t.Fatalf("--out: exit %d; stderr: %s", code, stderr)
	}
	data, _ := os.ReadFile(out)
	wantMatch(t, `(?s)^flowchart LR\n  accTitle: Architecture \(from the t snapshot\) — generated by codeshot\n.*n0 -->\|"1"\| n1\n$`, string(data))

	doc := filepath.Join(dir, "doc.md")
	if err := os.WriteFile(doc, []byte("# Doc\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if code, _, stderr := runCLI("--architecture", "--source", snap, "--format", "mermaid", "--embed", doc); code != 0 {
		t.Fatalf("--embed: exit %d; stderr: %s", code, stderr)
	}
	md, _ := os.ReadFile(doc)
	wantMatch(t, "(?s)<!-- codeshot:arch-snapshot-t:start -->\n```mermaid\nflowchart LR\n.*\n```\n<!-- codeshot:arch-snapshot-t:end -->", string(md))
	if matches, _ := filepath.Glob(filepath.Join(dir, "codeshot-*")); len(matches) != 0 {
		t.Errorf("--embed wrote an image file: %v", matches)
	}
	if code, stdout, stderr := runCLI("--architecture", "--source", snap, "--format", "mermaid", "--embed", doc, "--check"); code != 0 {
		t.Fatalf("--check current: exit %d; stderr: %s", code, stderr)
	} else {
		wantMatch(t, `up to date — the codeshot:arch-snapshot-t block`, stdout)
	}
	if err := os.WriteFile(doc, []byte(strings.Replace(string(md), `-->|"1"|`, `-->|"2"|`, 1)), 0o644); err != nil {
		t.Fatal(err)
	}
	if code, _, stderr := runCLI("--architecture", "--source", snap, "--format", "mermaid", "--embed", doc, "--check"); code != 1 {
		t.Errorf("--check stale: exit %d, want 1", code)
	} else {
		wantMatch(t, `the codeshot:arch-snapshot-t block in .* is out of date`, stderr)
	}
	wantRejected(t, `--format mermaid only applies with --architecture`, "Foo", "--format", "mermaid")
	wantRejected(t, `--format mermaid only applies with --architecture`, "--diff", "--format", "mermaid")
}
